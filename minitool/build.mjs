#!/usr/bin/env node
// Build the SBTI Xiaohongshu mini-tool: offline H5 bundle -> minitool/dist + minitool/sbti-minitool.zip
// Data is pulled from lib/*.ts so the mini-tool stays in sync with the website.
import { mkdirSync, rmSync, copyFileSync, writeFileSync, readdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const src = join(here, "src");
const dist = join(here, "dist");
const zipPath = join(here, "sbti-minitool.zip");

const { questions, drinkQuestions } = await import(join(root, "lib/questions.ts"));
const { personalityTypes } = await import(join(root, "lib/types.ts"));
const { DIMENSION_CODES, dimensionMeta, dimensionExplanations, modelGroups } = await import(
  join(root, "lib/dimensions.ts")
);

rmSync(dist, { recursive: true, force: true });
mkdirSync(join(dist, "assets"), { recursive: true });
mkdirSync(join(dist, "images"), { recursive: true });

// 1. Static files
for (const f of ["index.html"]) copyFileSync(join(src, f), join(dist, f));
for (const f of ["style.css", "app.js"]) copyFileSync(join(src, f), join(dist, "assets", f));

// 2. Images: downscale to 480px wide WebP (displayed at <=240 CSS px; 2x DPR)
const imgDir = join(root, "public/images/types");
const imageMap = {};
for (const file of readdirSync(imgDir)) {
  const slug = file.replace(/\.(png|jpe?g)$/i, "");
  if (slug === file) continue;
  const out = join(dist, "images", `${slug}.webp`);
  execFileSync("cwebp", ["-quiet", "-q", "78", "-resize", "480", "0", join(imgDir, file), "-o", out]);
  imageMap[slug] = `./images/${slug}.webp`;
}

// 3. Data module (classic script, attaches to window)
const data = {
  dimensionCodes: DIMENSION_CODES,
  dimensionMeta,
  dimensionExplanations,
  modelGroups,
  questions: questions.map((q) => ({ id: q.id, dim: q.dim, text: q.text, options: q.options })),
  drinkQuestions: drinkQuestions.map((q) => ({ id: q.id, kind: q.kind, text: q.text, options: q.options })),
  types: personalityTypes.map((t) => {
    if (!imageMap[t.slug]) throw new Error(`missing image for ${t.slug}`);
    return {
      code: t.code,
      cn: t.cn,
      slug: t.slug,
      intro: t.intro,
      desc: t.desc,
      pattern: t.pattern,
      special: !!t.special,
      image: imageMap[t.slug],
    };
  }),
};
writeFileSync(
  join(dist, "assets", "data.js"),
  `/* generated by minitool/build.mjs — do not edit */\nwindow.SBTI_DATA = ${JSON.stringify(data)};\n`
);

// 4. mini_tool.json — high-consumption marker. Reviewed: the bundle uses only DOM + Canvas 2D;
// no Worker, OffscreenCanvas, WebAssembly or game engine. Re-review if app.js changes.
writeFileSync(join(dist, "mini_tool.json"), JSON.stringify({ is_high_consumption_scene: false }) + "\n");

console.log(`dist ready: ${dist}`);
if (process.argv.includes("--no-zip")) process.exit(0);

// 5. Zip the *contents* of dist so index.html sits at the zip root
rmSync(zipPath, { force: true });
execFileSync("zip", ["-qr", "-X", zipPath, ".", "-x", "*.DS_Store"], { cwd: dist });
console.log(`zip ready: ${zipPath}`);
